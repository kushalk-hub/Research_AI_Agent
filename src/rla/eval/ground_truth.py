"""Ground-truth graph for the P8 evaluation.

The plan calls for a *hand-labelled* 20-paper reference graph, scored against the
auto-extracted one on node and edge precision/recall. This module owns the
schema, the loader, and -- deliberately -- the provenance rules.

Why provenance is a first-class field
-------------------------------------
A metric computed against a reference set that was itself generated by the same
model under test is not a measurement. It is a number that cannot come out badly.
So every reference set declares how it was made, `NodeProvenance`/`EdgeProvenance`
say who asserted each item, and `assess_reference_set` refuses to report node/edge
accuracy at all unless the set is `HAND_LABELLED`.

`load_reference_set` is the only way to get a `ReferenceSet` from disk, so an
unlabelled set cannot be passed off as ground truth by accident: the caller has
to notice the provenance and either label it or accept a non-scored evaluation.

What a human actually has to do
-------------------------------
Read 20 abstracts and write down, per paper, which concepts it is about and which
concept it extends or uses. That is `HAND_LABELLED`. It is slow, and doing it is
the user's call, not this module's -- so the file ships with a documented schema,
a `TemplateSet` builder that produces an empty form to fill in, and metrics that
are exercised against synthetic sets in the tests.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from enum import StrEnum
from pathlib import Path
from typing import Any

from pydantic import BaseModel, Field, model_validator

from rla.models import EdgeType

#: The plan's target. A smaller set still produces a number, but with a wider
#: confidence interval, and `assess_reference_set` reports the count so a reader
#: can see how thin it is.
TARGET_PAPERS = 20


class NodeProvenance(StrEnum):
    """Who asserted that a concept exists in the reference graph."""

    #: A person read the abstract and wrote it down. The only kind that supports
    #: a claim about extraction accuracy.
    HAND_LABELLED = "hand_labelled"
    #: Copied from the pipeline's own output. Useful for wiring up metrics and
    #: for regression tests; NOT a measurement of that pipeline.
    DERIVED = "derived"
    #: From citation metadata, which is ground truth by construction.
    CITATION_METADATA = "citation_metadata"


class EdgeProvenance(StrEnum):
    """Who asserted that a relation holds in the reference graph."""

    HAND_LABELLED = "hand_labelled"
    DERIVED = "derived"
    CITATION_METADATA = "citation_metadata"


class ReferenceNode(BaseModel):
    """A concept in the reference graph.

    `name` is the human-readable label; matching against the pipeline's concepts
    is by normalised name, because the pipeline mints its own `concept:` ids from
    slugs and those ids are not part of the ground truth.
    """

    name: str = Field(min_length=1)
    provenance: NodeProvenance = NodeProvenance.HAND_LABELLED
    #: Free-text note for the labeler, e.g. why they judged it a real concept.
    note: str = ""
    #: Ids of the papers this concept is about. Used to check that the reference
    #: set is self-consistent, not to score edge accuracy.
    paper_ids: list[str] = Field(default_factory=list)


class ReferenceEdge(BaseModel):
    """A relation in the reference graph.

    `source`/`target` are concept *names*, matching `ReferenceNode.name`. For a
    paper-to-concept relation, `source` is the paper id.
    """

    source: str = Field(min_length=1)
    target: str = Field(min_length=1)
    type: EdgeType
    provenance: EdgeProvenance = EdgeProvenance.HAND_LABELLED
    evidence: str = ""
    note: str = ""


class ReferenceSet(BaseModel):
    """A labelled subgraph plus the provenance needed to trust its metrics."""

    name: str = Field(min_length=1)
    #: Paper ids the labeller actually read.
    paper_ids: list[str] = Field(default_factory=list)
    nodes: list[ReferenceNode] = Field(default_factory=list)
    edges: list[ReferenceEdge] = Field(default_factory=list)
    #: Free text on how this set was produced. Required to be non-empty when the
    #: provenance is not hand-labelled, so a derived set always says so out loud.
    method: str = ""
    notes: str = ""

    @model_validator(mode="after")
    def _check(self) -> ReferenceSet:
        if len(self.paper_ids) < TARGET_PAPERS:
            # Not an error: partial label sets are legitimate while labelling is
            # in progress. `assess_reference_set` reports the shortfall instead,
            # because refusing to load would make incremental progress awkward.
            pass
        if not self.is_hand_labelled and not self.method:
            raise ValueError(
                "a reference set that is not hand-labelled must describe its method "
                f"in `method`; got provenance={[n.provenance for n in self.nodes]}"
            )
        return self

    @property
    def is_hand_labelled(self) -> bool:
        """True only when every item was hand-labelled.

        A single derived item is enough to disqualify the set, because a metric
        averaged over a mostly-truthful reference is still measuring the
        generator wherever the derived items are.
        """
        return all(n.provenance is NodeProvenance.HAND_LABELLED for n in self.nodes) and all(
            e.provenance is EdgeProvenance.HAND_LABELLED for e in self.edges
        )

    @property
    def hand_labelled_fraction(self) -> float:
        items = len(self.nodes) + len(self.edges)
        if not items:
            return 0.0
        hand = sum(1 for n in self.nodes if n.provenance is NodeProvenance.HAND_LABELLED)
        hand += sum(1 for e in self.edges if e.provenance is EdgeProvenance.HAND_LABELLED)
        return hand / items

    def concept_names(self) -> set[str]:
        return {n.name for n in self.nodes}

    def edge_keys(self) -> set[tuple[str, str, EdgeType]]:
        return {(e.source, e.target, e.type) for e in self.edges}


@dataclass
class ReferenceAssessment:
    """Whether a reference set can support the claims the report wants to make."""

    set_name: str
    papers: int
    nodes: int
    edges: int
    hand_labelled: bool
    hand_labelled_fraction: float
    #: Why the set cannot be scored, when it cannot. Empty when it can.
    blockers: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    @property
    def can_score_extraction(self) -> bool:
        """Node/edge precision/recall is only meaningful against hand labels."""
        return not self.blockers

    def to_dict(self) -> dict[str, Any]:
        return {
            "set": self.set_name,
            "papers": self.papers,
            "nodes": self.nodes,
            "edges": self.edges,
            "hand_labelled": self.hand_labelled,
            "hand_labelled_fraction": round(self.hand_labelled_fraction, 3),
            "can_score_extraction": self.can_score_extraction,
            "blockers": list(self.blockers),
            "warnings": list(self.warnings),
        }


def assess_reference_set(reference: ReferenceSet) -> ReferenceAssessment:
    """Decide what may be claimed from this reference set, and say why.

    The blockers are the point. A derived set blocks the accuracy claim; a small
    set warns about the interval without pretending the number is unusable.
    """
    blockers: list[str] = []
    warnings: list[str] = []

    if not reference.nodes and not reference.edges:
        blockers.append(
            "the reference set is empty, so there is nothing to score the "
            "extraction against"
        )
    if not reference.is_hand_labelled:
        derived_nodes = sum(
            1 for n in reference.nodes if n.provenance is not NodeProvenance.HAND_LABELLED
        )
        derived_edges = sum(
            1 for e in reference.edges if e.provenance is not EdgeProvenance.HAND_LABELLED
        )
        blockers.append(
            f"{derived_nodes} node(s) and {derived_edges} edge(s) are not hand-labelled "
            f"({reference.hand_labelled_fraction:.0%} hand-labelled). Node/edge precision "
            "and recall measure agreement with whoever wrote the set, so a set built from "
            "the pipeline's own output cannot be used to evaluate that pipeline. "
            "Score nothing here, or hand-label the set first."
        )
    if reference.paper_ids and len(reference.paper_ids) < TARGET_PAPERS:
        warnings.append(
            f"{len(reference.paper_ids)} paper(s) labelled against a target of "
            f"{TARGET_PAPERS}; recall rests on few items, so treat it as indicative"
        )
    if not reference.paper_ids:
        warnings.append("the set lists no paper ids, so it cannot be joined to the corpus")

    return ReferenceAssessment(
        set_name=reference.name,
        papers=len(reference.paper_ids),
        nodes=len(reference.nodes),
        edges=len(reference.edges),
        hand_labelled=reference.is_hand_labelled,
        hand_labelled_fraction=reference.hand_labelled_fraction,
        blockers=blockers,
        warnings=warnings,
    )


def load_reference_set(path: Path) -> ReferenceSet:
    """Read a reference set from `eval/ground_truth.json`."""
    data = json.loads(Path(path).read_text("utf-8"))
    return ReferenceSet.model_validate(data)


def empty_template(name: str = "p8-reference") -> ReferenceSet:
    """A blank form to hand-label, with the schema filled in.

    Ships empty on purpose: a populated template that looks hand-made is exactly
    the thing that would let a derived set pass for a real one later.
    """
    return ReferenceSet(
        name=name,
        method="",
        notes=(
            "Fill in `paper_ids` with the papers you read, one `ReferenceNode` per concept "
            "you judged them to be about, and one `ReferenceEdge` per EXTENDS/USES/INTRODUCES "
            "relation you are confident of. Leave provenance at hand_labelled. Skip relations "
            "you are unsure about: a smaller confident set gives an honest recall number, "
            "whereas a guessed one does not."
        ),
    )


def render_template(reference: ReferenceSet, path: Path) -> None:
    """Write a template out for labelling."""
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(
        json.dumps(reference.model_dump(mode="json"), indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
